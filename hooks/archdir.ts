// Where the ARCH panel's diagrams live and how clicks move through them: the system and repo layers, breadcrumbs, likec4 output.
// Pure; register.tsx lists the folders, runs likec4 and keeps the cache.

import type { ArchNode } from './arch'
import type { ArchState, UiState } from './views'

export const ARCH_EXT = /\.(c4|likec4)$/
export const SYSTEM_MAPS = '02-Architecture/system-maps'
export const isSystemMaps = (dir: string) => dir.endsWith(`/${SYSTEM_MAPS}`)

/** A directory entry that is a LikeC4 source file. */
export const isC4File = (f: { kind: string; name: string }) => f.kind === 'file' && ARCH_EXT.test(f.name)

/** a/b/../c → a/c. A repo in a .c4 file is a path relative to the diagram's directory. */
export const joinPath = (dir: string, rel: string) => {
  const parts: string[] = []
  for (const seg of (rel.startsWith('/') ? rel : `${dir}/${rel}`).split('/')) {
    if (seg === '..') parts.pop()
    else if (seg && seg !== '.') parts.push(seg)
  }
  return `/${parts.join('/')}`
}

/** Starting trail: inside a repo, "system layer (if found) → the repo's docs/"; outside a repo, the system layer or cwd/docs. */
export function archBaseFrom(root: string | undefined, sys: string | undefined, cwd: string): string[] {
  if (root) return sys ? [sys, `${root}/docs`] : [`${root}/docs`]
  return sys ? [sys] : [`${cwd}/docs`]
}

/** Breadcrumb label for a directory: the workspace folder name (the vault's parent) for the system layer, the repo name for a repo layer. */
export const archDirLabel = (dir: string) => {
  const parts = dir.split('/')
  return isSystemMaps(dir) ? parts.at(-4) ?? 'system' : parts.at(-2) ?? dir
}

/** How the likec4 command line is named to the agent and in messages. */
export const likec4Label = (cli: readonly string[]) => (cli[0] === 'npx' ? 'npx likec4' : cli[0]!)

// likec4 error messages carry ANSI color codes and start with "Line N: ".
export const likec4Errors = (out: string) =>
  out.replace(/\x1b\[[0-9;]*m/g, '').split('\n').map(l => l.trim()).filter(l => /^Line \d+:/.test(l) || /^Error/i.test(l)).slice(0, 5).join('\n')

/** "name:mtime" of every .c4 file in a folder: when it is unchanged the folder needs no new export. */
export const archStamp = (files: readonly { name: string; mtimeMs: number }[]) => files.map(f => `${f.name}:${f.mtimeMs}`).sort().join('|')

/** The views/<id>.md written beside the system layer for Obsidian, which renders mermaid blocks but can't read .c4. */
export const mermaidDoc = (title: string, mmd: string) =>
  `# ${title}\n\n> Generated by asint from the LikeC4 model in this folder. Edit the \`.c4\` file, not this one.\n\n\`\`\`mermaid\n${mmd.trim()}\n\`\`\`\n`

type ArchUi = Pick<UiState, 'archTrail' | 'archDirs' | 'archSel' | 'archPanX' | 'scroll'>

/** Nothing selected, no pan, scrolled to the top: how every new view or layer starts. */
function freshView(ui: ArchUi) {
  ui.archSel = undefined
  ui.archPanX = 0
  ui.scroll.arch = 0
}

/** cwd moved to another starting trail: start over at its last layer, on the overview. */
export function archRebase(ui: ArchUi, base: string[]) {
  ui.archDirs = base
  ui.archTrail = []
  ui.archSel = undefined
}

/** If the selected view disappeared (renamed, deleted), go back to the overview. */
export function archPrune(ui: ArchUi, arch: ArchState | undefined) {
  if (arch?.model && !ui.archTrail.every(id => arch.model!.views[id])) { ui.archTrail = []; ui.archSel = undefined }
}

/**
 * A click on a node. First click selects; clicking a selected node that can drill down enters it; clicking a selected
 * system-layer element pointing at a repo switches to that repo's docs/ diagram and adds a breadcrumb. True when the layer changed and must be loaded.
 */
export function archPress(ui: ArchUi, n: ArchNode, arch: ArchState | undefined): boolean {
  if (ui.archSel === n.id && n.navigateTo) {
    const model = arch?.model
    const trail = ui.archTrail.length ? ui.archTrail : model ? [model.first] : []
    ui.archTrail = [...trail, n.navigateTo]
    freshView(ui)
    return false
  }
  if (ui.archSel === n.id && n.repo && arch) {
    ui.archDirs = [...ui.archDirs, `${joinPath(arch.dir, n.repo)}/docs`]
    ui.archTrail = []
    freshView(ui)
    return true
  }
  ui.archSel = n.id
  return false
}

/** Back to layer i of the breadcrumb (system layer, repo, …); the caller loads it. */
export function archUp(ui: ArchUi, i: number) {
  ui.archDirs = ui.archDirs.slice(0, i + 1)
  ui.archTrail = []
  freshView(ui)
}

/** Back to view i of the current layer's breadcrumb. */
export function archBack(ui: ArchUi, i: number) {
  ui.archTrail = ui.archTrail.slice(0, i + 1)
  freshView(ui)
}
